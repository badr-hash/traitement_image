# Question 1 : symétrie autour de l'axe vertical médian
# ---------------------------------------------------------------------------
def symetrie(im):
    n, p, c = im.shape
    im_sym = np.zeros_like(im)
    for i in range(n):
        for j in range(p):
            im_sym[i, j] = im[i, p - 1 - j]
    return im_sym


